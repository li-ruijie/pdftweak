#!/usr/bin/env pwsh
# Generates src/core/pdf/helvetica.cpp, the widths and glyph boxes of Helvetica for the 256 codes of
# WinAnsiEncoding, from Helvetica.afm in the iText jar, as iText's Type1Font computes them: each byte
# decodes to Unicode as Cp1252 does in iText's PdfEncodings, the Unicode value takes its glyph name
# from iText's glyphlist.txt (the last name listed for a value wins), and the name finds its metrics
# in the AFM. Codes without a glyph get width 0 and no box.
#
#   pwsh tools/gen-helvetica.ps1 -Jar path\to\itextpdf-5.5.13.6.jar

param(
    [Parameter(Mandatory)]
    [string]$Jar
)

$ErrorActionPreference = 'Stop'
Add-Type -AssemblyName System.IO.Compression.FileSystem

function Read-JarEntry([string]$name) {
    $zip = [System.IO.Compression.ZipFile]::OpenRead($Jar)
    try {
        $entry = $zip.GetEntry($name)
        if ($null -eq $entry) { throw "$name is not in $Jar" }
        $reader = [System.IO.StreamReader]::new($entry.Open(), [System.Text.Encoding]::Latin1)
        try { return $reader.ReadToEnd() } finally { $reader.Dispose() }
    } finally {
        $zip.Dispose()
    }
}

$afm = Read-JarEntry 'com/itextpdf/text/pdf/fonts/Helvetica.afm'
$readme = Read-JarEntry 'com/itextpdf/text/pdf/fonts/mustRead.html'
$glyphList = Read-JarEntry 'com/itextpdf/text/pdf/fonts/glyphlist.txt'

# iText's PdfEncodings.winansiByteToChar for 0x80 to 0x9F, with 65533 for the codes Cp1252 leaves
# undefined. The other codes decode to the same value.
$high = @(8364, 65533, 8218, 402, 8222, 8230, 8224, 8225, 710, 8240, 352, 8249, 338, 65533, 381, 65533,
    65533, 8216, 8217, 8220, 8221, 8226, 8211, 8212, 732, 8482, 353, 8250, 339, 65533, 382, 376)

$names = @{}
foreach ($line in $glyphList -split "`r?`n") {
    if ($line.StartsWith('#')) { continue }
    $fields = $line -split '[ ;\t\f]+' | Where-Object { $_ -ne '' }
    if ($fields.Count -lt 2) { continue }
    $names[[Convert]::ToInt32($fields[1], 16)] = $fields[0]
}

# glyph names differ only in case (A and a), so the table compares them ordinally
$metrics = [System.Collections.Generic.Dictionary[string, object]]::new([System.StringComparer]::Ordinal)
foreach ($line in $afm -split "`r?`n") {
    if ($line -match '^C\s+-?\d+\s*;\s*WX\s+(\d+)\s*;\s*N\s+(\S+)\s*;\s*B\s+(-?\d+)\s+(-?\d+)\s+(-?\d+)\s+(-?\d+)') {
        $metrics[$Matches[2]] = @([int]$Matches[1], [int]$Matches[3], [int]$Matches[4], [int]$Matches[5],
            [int]$Matches[6])
    }
}

# Type1Font gives a font without nonbreakingspace the metrics of its space
if (-not $metrics.ContainsKey('nonbreakingspace') -and $metrics.ContainsKey('space')) {
    $metrics['nonbreakingspace'] = $metrics['space']
}

$copyright = ($afm -split "`r?`n" | Where-Object { $_ -like 'Comment Copyright*' } | Select-Object -First 1).
    Substring('Comment '.Length)
if ($readme -notmatch '<td width="300">(.*?) <font') { throw 'The paragraph of mustRead.html was not found' }
$paragraph = $Matches[1]

# A comment block of lines no wider than 108 columns.
function Format-Comment([string]$text) {
    $lines = @()
    $line = '//'
    foreach ($word in $text -split ' ') {
        if (($line.Length + 1 + $word.Length) -gt 108) {
            $lines += $line
            $line = '//'
        }
        $line += " $word"
    }
    return ($lines + $line) -join "`n"
}

$rows = @()
for ($code = 0; $code -lt 256; $code++) {
    $unicode = if ($code -ge 0x80 -and $code -le 0x9F) { $high[$code - 0x80] } else { $code }
    $name = $names[$unicode]
    $m = if ($null -ne $name -and $metrics.ContainsKey($name)) { $metrics[$name] } else { $null }
    if ($null -eq $m) {
        $rows += "    {0, false, 0, 0, 0, 0}, // $code"
    } else {
        $rows += "    {$($m[0]), true, $($m[1]), $($m[2]), $($m[3]), $($m[4])}, // $code $name"
    }
}

$source = @"
// Generated by tools/gen-helvetica.ps1. Do not edit.
//
// Derived from Helvetica.afm in the iText 5.5.13.6 jar (Adobe Systems, Creation Date: Thu May  1
// 12:38:23 1997), reduced to the 256 codes of WinAnsiEncoding as iText's Type1Font maps them, and
// carrying the advance widths and glyph boxes only. The AFM file states:
//
// $copyright
//
// The mustRead.html file that accompanies the AFM files states:
//
$(Format-Comment $paragraph)

#include "core/pdf/helvetica.h"

namespace pdftweak::pdf::helvetica {

const GlyphMetrics kMetrics[256] = {
$($rows -join "`n")
};

} // namespace pdftweak::pdf::helvetica
"@

$target = Join-Path $PSScriptRoot '..\src\core\pdf\helvetica.cpp'
[System.IO.File]::WriteAllText($target, $source.Replace("`r`n", "`n") + "`n", [System.Text.UTF8Encoding]::new($false))
Write-Host "Wrote $target"
